#!/usr/bin/env bash

## Neo Brutalism theme switcher for sway / waybar / mako / wofi / rofi / terminals
##
## Usage: neobrutal.sh light | dark | toggle | apply | status
##        neobrutal.sh accent yellow|red|blue|green|purple|orange|cyan|pink|default
##        neobrutal.sh cursor-size 24|32|48|72|default
##        neobrutal.sh zoom 80|90|100|110|120|default

DIR="$HOME/.config/sway"
THEME_DIR="$DIR/theme/neobrutal"
STATE_FILE="$DIR/theme/.neobrutal_mode"
ACCENT_FILE="$DIR/theme/.neobrutal_accent"
ACCENTS=(yellow red blue green purple orange cyan pink)
CURSOR_SIZE_FILE="$DIR/theme/.neobrutal_cursor_size"
CURSOR_SIZES=(24 32 48 72)   # the sizes theme/cursor/build.sh renders
ZOOM_FILE="$DIR/theme/.neobrutal_zoom"
ZOOMS=(80 90 100 110 120)  # percent, = sway output scale
WALL_DIR="$DIR/wallpapers"

current_mode() {
	local mode
	mode="$(cat "$STATE_FILE" 2>/dev/null)"
	[[ "$mode" == "light" || "$mode" == "dark" ]] && echo "$mode" || echo "light"
}

## Accent picked in the theme panel : one color for both main and accent
## (sway borders, waybar, menus, cursor…). No file = the palette defaults.
apply_accent_choice() {
	local name
	name="$(cat "$ACCENT_FILE" 2>/dev/null)"
	if [[ " ${ACCENTS[*]} " == *" $name "* ]]; then
		main="${!name}"
		accent="${!name}"
		accent_name="$name"
	fi
	cursor_theme="Neobrutal-${accent_name^}"
}

## Zoom picked in the theme panel (whole system = sway output scale). Default 100%.
apply_zoom_choice() {
	local z
	z="$(cat "$ZOOM_FILE" 2>/dev/null)"
	[[ " ${ZOOMS[*]} " == *" $z "* ]] && zoom="$z" || zoom=100
	return 0
}

## Sway : output scale + positions. The positions in config are for 100% ;
## a scaled output is smaller in layout coordinates, so they are divided by
## the scale too (otherwise screens overlap or leave a gap between them).
apply_zoom() {
	local scale outputs name x y cmds=()
	# LC_ALL=C : mawk (Ubuntu) follows the locale and would write 1,1 instead of 1.1
	scale="$(LC_ALL=C awk -v z="$zoom" 'BEGIN { printf "%g", z / 100 }')"
	# "output <name|$var> pos X Y" lines of config, $vars resolved from "set $var NAME"
	outputs="$(awk '
		$1 == "set" && $2 ~ /^\$/ { v = $3; gsub(/"/, "", v); vars[$2] = v }
		$1 == "output" {
			n = $2; if (n in vars) n = vars[n]
			for (i = 3; i < NF; i++) if ($i == "pos") print n, $(i + 1), $(i + 2)
		}' "$DIR/config")"

	{
		echo "## Generated by theme/neobrutal.sh (zoom ${zoom}%) — do not edit"
		echo "output * scale $scale"
		while read -r name x y; do
			[[ -n "$name" ]] || continue
			printf 'output %s pos %d %d\n' "$name" \
				"$(LC_ALL=C awk -v p="$x" -v s="$scale" 'BEGIN { printf "%d", p / s + 0.5 }')" \
				"$(LC_ALL=C awk -v p="$y" -v s="$scale" 'BEGIN { printf "%d", p / s + 0.5 }')"
		done <<< "$outputs"
	} > "$DIR/sway-zoom"

	# live : only when the scale changes (re-applying it makes outputs flicker)
	local current
	current="$(swaymsg -t get_outputs 2>/dev/null | jq -r '.[] | select(.active) | .scale')" || return 0
	[[ -z "$current" ]] && return 0
	# sway reports 0.8 as 0.80000001… : compare with a tolerance
	LC_ALL=C awk -v s="$scale" '{ d = $1 - s; if (d > 0.001 || d < -0.001) changed = 1 } END { exit !changed }' <<< "$current" || return 0
	while read -r line; do
		[[ "$line" == output* ]] && cmds+=("$line")
	done < "$DIR/sway-zoom"
	swaymsg -q "$(IFS=';'; echo "${cmds[*]}")" 2>/dev/null
	return 0
}

## Cursor size picked in the theme panel. No file = the palette default.
apply_cursor_size_choice() {
	local size
	size="$(cat "$CURSOR_SIZE_FILE" 2>/dev/null)"
	[[ " ${CURSOR_SIZES[*]} " == *" $size "* ]] && cursor_size="$size"
	return 0
}

## Wallpaper : flat bg + dot grid tile (same as the SDDM theme) ----------
apply_wallpaper() {
	WALLPAPER="$WALL_DIR/neobrutal-$MODE.png"
	mkdir -p "$WALL_DIR"
	local im="magick"; command -v magick >/dev/null 2>&1 || im="convert"
	# dot color : grid lightened (dark) or darkened (light), like Qt.darker in SDDM
	local k; [[ "$MODE" == "dark" ]] && k=160 || k=89   # percent
	local hex="${grid#\#}" dot="" i v
	for i in 0 2 4; do
		v=$(( (16#${hex:i:2} * k + 50) / 100 ))
		(( v > 255 )) && v=255
		dot+="$(printf '%02X' "$v")"
	done
	# one 2.5px dot centered in a 32px tile
	"$im" -size 32x32 "xc:$bg" \
		-fill "#$dot" -draw "circle 16,16 18.5,16" \
		"$WALLPAPER"
	swaymsg -q "output * bg $WALLPAPER tile" 2>/dev/null
}

## Sway : borders, titlebars, gtk -----------
apply_sway() {
	cat > "$DIR/sway-colors" <<- _EOF_
		## Generated by theme/neobrutal.sh ($MODE) — do not edit, edit the palette instead.

		# target                 title     bg         text   indicator  border
		client.focused           $border   $accent    $ink   $blue      $accent
		client.focused_inactive  $border   $surface   $fg    $border    $border
		client.unfocused         $border   $bg        $fg    $border    $border
		client.urgent            $border   $red       $ink   $red       $red
		client.placeholder       $border   $bg        $fg    $border    $border
		client.background        $bg

		output * bg $WALLPAPER tile
		seat * xcursor_theme $cursor_theme $cursor_size

		exec_always {
		    gsettings set org.gnome.desktop.interface gtk-theme '$gtk_theme'
		    gsettings set org.gnome.desktop.interface icon-theme '$gtk_icons'
		    gsettings set org.gnome.desktop.interface cursor-theme '$cursor_theme'
		    gsettings set org.gnome.desktop.interface cursor-size $cursor_size
		    gsettings set org.gnome.desktop.interface color-scheme '$gtk_scheme'
		}
	_EOF_

	# live apply, without a full reload (which would restart waybar/mako)
	swaymsg -q "client.focused $border $accent $ink $blue $accent" 2>/dev/null
	swaymsg -q "client.focused_inactive $border $surface $fg $border $border" 2>/dev/null
	swaymsg -q "client.unfocused $border $bg $fg $border $border" 2>/dev/null
	swaymsg -q "client.urgent $border $red $ink $red $red" 2>/dev/null
	swaymsg -q "client.placeholder $border $bg $fg $border $border" 2>/dev/null
	swaymsg -q "seat * xcursor_theme $cursor_theme $cursor_size" 2>/dev/null

	gsettings set org.gnome.desktop.interface gtk-theme "$gtk_theme"
	gsettings set org.gnome.desktop.interface icon-theme "$gtk_icons"
	gsettings set org.gnome.desktop.interface cursor-theme "$cursor_theme"
	gsettings set org.gnome.desktop.interface cursor-size "$cursor_size"
	apply_cursor_pointers
	gsettings set org.gnome.desktop.interface color-scheme "$gtk_scheme"
}

## Cursor : "Neobrutal" is a pointer theme (index.theme only) inheriting the
## current variant, for apps that don't follow sway (X11 apps via ~/.icons/default)
## and the SDDM greeter (/usr/share/icons/Neobrutal, owned by you, see sddm/install.sh)
apply_cursor_pointers() {
	[[ "$cursor_theme" == Neobrutal-* ]] || return 0
	local d content
	content="$(printf '[Icon Theme]\nName=Neobrutal\nComment=Points to the current accent, written by theme/neobrutal.sh\nInherits=%s\n' "$cursor_theme")"
	d="${XDG_DATA_HOME:-$HOME/.local/share}/icons/Neobrutal"
	mkdir -p "$d" && printf '%s\n' "$content" > "$d/index.theme"
	d="/usr/share/icons/Neobrutal"
	[[ -w "$d/index.theme" ]] && printf '%s\n' "$content" > "$d/index.theme"
	return 0
}

## GTK-CSS palette (waybar, wlogout) --------
gtk_palette() {
	cat <<- _EOF_
		/** Generated by theme/neobrutal.sh ($MODE) **/
		@define-color bg      $bg;
		@define-color surface $surface;
		@define-color fg      $fg;
		@define-color ink     $ink;
		@define-color border  $border;
		@define-color shadow  $shadow;
		@define-color muted   $muted;
		@define-color main    $main;
		@define-color accent  $accent;
		@define-color yellow  $yellow;
		@define-color red     $red;
		@define-color blue    $blue;
		@define-color green   $green;
		@define-color purple  $purple;
		@define-color orange  $orange;
		@define-color cyan    $cyan;
		@define-color pink    $pink;
	_EOF_
}

apply_waybar() {
	gtk_palette > "$DIR/waybar/colors.css"
	pkill -SIGUSR2 -x waybar 2>/dev/null
	pkill -RTMIN+8 -x waybar 2>/dev/null   # custom/theme icon
}

apply_wlogout() {
	gtk_palette > "$DIR/wlogout/colors.css"
}

