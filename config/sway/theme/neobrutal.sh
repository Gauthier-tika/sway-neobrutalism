	cat > "$DIR/alacritty/colors.toml" <<- _EOF_
		## Generated by theme/neobrutal.sh ($MODE)
		[colors.primary]
		background = "$term_bg"
		foreground = "$term_fg"

		[colors.cursor]
		text   = "$term_bg"
		cursor = "$term_fg"

		[colors.selection]
		text       = "$ink"
		background = "$main"

		[colors.normal]
		black   = "$color0"
		red     = "$color1"
		green   = "$color2"
		yellow  = "$color3"
		blue    = "$color4"
		magenta = "$color5"
		cyan    = "$color6"
		white   = "$color7"

		[colors.bright]
		black   = "$color8"
		red     = "$color9"
		green   = "$color10"
		yellow  = "$color11"
		blue    = "$color12"
		magenta = "$color13"
		cyan    = "$color14"
		white   = "$color15"
	_EOF_
}

