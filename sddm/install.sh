#!/usr/bin/env bash
#
# Neo Brutalism SDDM theme — installer
#
#   sddm/install.sh                install the theme and make it the current SDDM theme
#   sddm/install.sh --test         preview it in a window (sddm-greeter --test-mode), no root needed
#
# The palettes come from config/sway/theme/neobrutal/{light,dark}.bash.
# theme.conf.user (owned by you) holds the light/dark mode : theme/neobrutal.sh keeps it in sync.

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$REPO/sddm/neobrutal"
PALETTES="$REPO/config/sway/theme/neobrutal"
DEST="/usr/share/sddm/themes/neobrutal"
CONF="/etc/sddm.conf.d/zz-neobrutal.conf"
MODE_FILE="${XDG_CONFIG_HOME:-$HOME/.config}/sway/theme/.neobrutal_mode"
KEYS=(bg grid surface fg ink border shadow muted main accent yellow red blue green purple orange cyan pink)

mode="$(cat "$MODE_FILE" 2>/dev/null || true)"
[[ "$mode" == light || "$mode" == dark ]] || mode="dark"

# theme.conf : both palettes, prefixed light_ / dark_
gen_conf() {
	echo "# Generated by sddm/install.sh — edit config/sway/theme/neobrutal/*.bash instead"
	echo "[General]"
	echo "mode=$mode"
	echo "font=JetBrainsMono Nerd Font"
	local m k
	for m in light dark; do
		echo
		# shellcheck source=/dev/null
		( source "$PALETTES/$m.bash"; for k in "${KEYS[@]}"; do printf '%s_%s="%s"\n' "$m" "$k" "${!k}"; done )
	done
}

build() {
	local out="$1"
	mkdir -p "$out"
	cp "$SRC/Main.qml" "$SRC/metadata.desktop" "$out/"
	gen_conf > "$out/theme.conf"
}

if [[ "${1:-}" == "--test" ]]; then
	tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
	build "$tmp/neobrutal"
	greeter="$(command -v sddm-greeter-qt6 || command -v sddm-greeter)"
	"$greeter" --test-mode --theme "$tmp/neobrutal"
	exit
fi

[[ $EUID -eq 0 ]] && { echo "run as your normal user (sudo is used when needed)" >&2; exit 1; }
command -v sddm >/dev/null || { echo "sddm is not installed" >&2; exit 1; }

tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
build "$tmp/neobrutal"
printf '[General]\nmode=%s\n' "$mode" > "$tmp/neobrutal/theme.conf.user"

sudo rm -rf "$DEST"
sudo install -d "$DEST"
sudo install -m 644 "$tmp/neobrutal/"{Main.qml,metadata.desktop,theme.conf} "$DEST/"
# only the mode file is yours, so the light/dark switch works without sudo
sudo install -m 644 -o "$USER" "$tmp/neobrutal/theme.conf.user" "$DEST/"

sudo install -d /etc/sddm.conf.d
printf '# Generated by sddm/install.sh\n[Theme]\nCurrent=neobrutal\n' | sudo tee "$CONF" >/dev/null

# avatar : the greeter can't read ~/.face (home is private), give it a copy
for f in "$HOME/.face.icon" "$HOME/.face"; do
	if [[ -f "$f" ]]; then
		sudo install -m 644 "$f" "/usr/share/sddm/faces/$USER.face.icon"
		break
	fi
done

echo "✓ SDDM theme installed ($DEST, $mode) and enabled in $CONF"
