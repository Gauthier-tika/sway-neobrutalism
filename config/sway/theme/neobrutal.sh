## Hyprlock (hyprlock.conf sources hyprlock-colors.conf)
apply_hyprlock() {
	rgba() { printf 'rgba(%d, %d, %d, %s)' "0x${1:1:2}" "0x${1:3:2}" "0x${1:5:2}" "$2"; }
	cat > "$DIR/hyprlock-colors.conf" <<- _EOF_
		# Generated by theme/neobrutal.sh ($MODE)
		\$wallpaper = $WALLPAPER
		\$accent_color = $(rgba "$main" 1.0)
		\$text_color = $(rgba "$fg" 1.0)
		\$text_color_hex = $fg
		\$inner_color = $(rgba "$surface" 1.0)
		\$outer_color = $(rgba "$border" 1.0)
		\$check_color = $(rgba "$green" 1.0)
		\$fail_color = $(rgba "$red" 1.0)
	_EOF_
}

## Chromium (unpacked theme extension) ------
## Load once via chrome://extensions > Developer mode > Load unpacked > ~/.config/sway/chromium/neobrutal-theme
## Chromium re-reads it from disk on restart (or via the reload button on chrome://extensions).
apply_chromium() {
	local cdir="$DIR/chromium/neobrutal-theme"
	rgb() { printf '[%d, %d, %d]' "0x${1:1:2}" "0x${1:3:2}" "0x${1:5:2}"; }
	mkdir -p "$cdir/images"
	cp "$WALLPAPER" "$cdir/images/grid.png"

	# light : yellow toolbar/active tab, dark : neutral toolbar, yellow omnibox focus
	local toolbar toolbar_fg
	if [[ "$MODE" == "light" ]]; then
		toolbar="$main"; toolbar_fg="$ink"
	else
		toolbar="$surface"; toolbar_fg="$fg"
	fi

	cat > "$cdir/manifest.json" <<- _EOF_
		{
		  "manifest_version": 3,
		  "name": "Neo Brutalism ($MODE)",
		  "version": "1.0.$( [[ "$MODE" == "light" ]] && echo 1 || echo 2 )",
		  "description": "Generated by ~/.config/sway/theme/neobrutal.sh",
		  "theme": {
		    "images": {
		      "theme_frame": "images/grid.png",
		      "theme_frame_inactive": "images/grid.png",
		      "theme_ntp_background": "images/grid.png"
		    },
		    "colors": {
		      "frame": $(rgb "$bg"),
		      "frame_inactive": $(rgb "$bg"),
		      "frame_incognito": $(rgb "$border"),
		      "frame_incognito_inactive": $(rgb "$border"),
		      "toolbar": $(rgb "$toolbar"),
		      "toolbar_text": $(rgb "$toolbar_fg"),
		      "toolbar_button_icon": $(rgb "$toolbar_fg"),
		      "tab_text": $(rgb "$toolbar_fg"),
		      "tab_background_text": $(rgb "$fg"),
		      "tab_background_text_inactive": $(rgb "$muted"),
		      "bookmark_text": $(rgb "$toolbar_fg"),
		      "omnibox_background": $(rgb "$surface"),
		      "omnibox_text": $(rgb "$fg"),
		      "button_background": $(rgb "$surface"),
		      "ntp_background": $(rgb "$bg"),
		      "ntp_text": $(rgb "$fg"),
		      "ntp_link": $(rgb "$accent"),
		      "ntp_header": $(rgb "$main")
		    },
		    "tints": {
		      "buttons": [-1, -1, -1]
		    },
		    "properties": {
		      "ntp_background_alignment": "top",
		      "ntp_background_repeat": "repeat"
		    }
		  }
		}
	_EOF_
}

## Quickshell (panels) : live-reloaded json --
