## GTK fallbacks when the preferred themes aren't installed (vanilla Arch / Ubuntu)
gtk_fallbacks() {
	theme_exists() { for d in "$HOME/.themes" "$HOME/.local/share/themes" /usr/share/themes; do [[ -d "$d/$1" ]] && return 0; done; return 1; }
	icons_exist() { for d in "$HOME/.icons" "$HOME/.local/share/icons" /usr/share/icons; do [[ -d "$d/$1" ]] && return 0; done; return 1; }

	if ! theme_exists "$gtk_theme"; then
		if theme_exists "adw-gtk3"; then
			[[ "$MODE" == "dark" ]] && gtk_theme="adw-gtk3-dark" || gtk_theme="adw-gtk3"
		else
			[[ "$MODE" == "dark" ]] && gtk_theme="Adwaita-dark" || gtk_theme="Adwaita"
		fi
	fi
	if ! icons_exist "$gtk_icons"; then
		if icons_exist "Papirus"; then
			[[ "$MODE" == "dark" ]] && gtk_icons="Papirus-Dark" || gtk_icons="Papirus-Light"
		else
			gtk_icons="Adwaita"
		fi
	fi
	icons_exist "$cursor_theme" || cursor_theme="Adwaita"   # theme/cursor/build.sh not run
}

## SDDM (login screen) : only the mode, the palettes are baked in by sddm/install.sh
apply_sddm() {
	local f="/usr/share/sddm/themes/neobrutal/theme.conf.user"
	[[ -w "$f" ]] && printf '[General]\nmode=%s\nmain=%s\naccent=%s\n' "$MODE" "$main" "$accent" > "$f"
	return 0
}

apply_all() {
	MODE="$1"
	# shellcheck source=/dev/null
	source "$THEME_DIR/$MODE.bash"
	apply_accent_choice
	apply_cursor_size_choice
	apply_zoom_choice
	gtk_fallbacks
	echo "$MODE" > "$STATE_FILE"

	apply_wallpaper
	apply_sway
	apply_zoom
	apply_wofi
	apply_rofi
	apply_wlogout
	apply_mako
	apply_alacritty
	apply_kitty
	apply_foot
	apply_hyprlock
	apply_chromium
	apply_quickshell
	apply_sddm
	apply_waybar
}

case "$1" in
	light|dark) apply_all "$1" ;;
	toggle)     [[ "$(current_mode)" == "light" ]] && apply_all dark || apply_all light ;;
	apply)      apply_all "$(current_mode)" ;;
	status)     current_mode ;;
	accent)
		if [[ "$2" == default ]]; then
			rm -f "$ACCENT_FILE"
		elif [[ " ${ACCENTS[*]} " == *" $2 "* ]]; then
			echo "$2" > "$ACCENT_FILE"
		else
			echo "Usage: ${0##*/} accent $(IFS="|"; echo "${ACCENTS[*]}")|default"; exit 1
		fi
		apply_all "$(current_mode)"
		;;
	cursor-size)
		if [[ "$2" == default ]]; then
			rm -f "$CURSOR_SIZE_FILE"
		elif [[ " ${CURSOR_SIZES[*]} " == *" $2 "* ]]; then
			echo "$2" > "$CURSOR_SIZE_FILE"
		else
			echo "Usage: ${0##*/} cursor-size $(IFS="|"; echo "${CURSOR_SIZES[*]}")|default"; exit 1
		fi
		apply_all "$(current_mode)"
		;;
	zoom)
		if [[ "$2" == default ]]; then
			rm -f "$ZOOM_FILE"
		elif [[ " ${ZOOMS[*]} " == *" ${2%\%} "* ]]; then
			echo "${2%\%}" > "$ZOOM_FILE"
		else
			echo "Usage: ${0##*/} zoom $(IFS="|"; echo "${ZOOMS[*]}")|default"; exit 1
		fi
		apply_all "$(current_mode)"
		;;
	*)          echo "Usage: ${0##*/} light | dark | toggle | apply | status | accent <color> | cursor-size <px> | zoom <percent>"; exit 1 ;;
esac
